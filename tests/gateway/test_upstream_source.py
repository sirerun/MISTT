import gzip
import hashlib
import io
import tarfile
import tempfile
import unittest
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import patch

from dgx.gateway import upstream_source


class UpstreamSourceTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.root_name = "VibeVoice-testcommit"
        self.archive = self.root / "download.tar.gz"
        self.cache_archive = self.root / "upstream.tar.gz"
        self.source = self.root / "source"
        self.patches = [
            patch.object(upstream_source, "SOURCE_COMMIT", "testcommit"),
            patch.object(upstream_source, "ARCHIVE_ROOT", self.root_name),
            patch.object(upstream_source, "ARCHIVE_SHA256", ""),
        ]
        for item in self.patches:
            item.start()
        self.addCleanup(self._stop_patches)

    def _stop_patches(self):
        for item in reversed(self.patches):
            item.stop()
        self.temp.cleanup()

    def make_archive(self, *, extra=None):
        rows = {
            f"{self.root_name}/": ("dir", b"", 0o775),
            f"{self.root_name}/pkg/": ("dir", b"", 0o775),
            f"{self.root_name}/pyproject.toml": ("file", b"[build-system]\n", 0o664),
            f"{self.root_name}/pkg/__init__.py": ("file", b"VERSION = 'pinned'\n", 0o664),
            f"{self.root_name}/bin/run": ("file", b"#!/bin/sh\n", 0o775),
        }
        if extra:
            rows.update(extra)
        with self.archive.open("wb") as raw:
            with gzip.GzipFile(fileobj=raw, mode="wb", mtime=0) as compressed:
                with tarfile.open(fileobj=compressed, mode="w|", format=tarfile.PAX_FORMAT) as archive:
                    for name, (kind, data, mode) in rows.items():
                        member = tarfile.TarInfo(name)
                        member.mode = mode
                        if kind == "dir":
                            member.type = tarfile.DIRTYPE
                            archive.addfile(member)
                        elif kind == "symlink":
                            member.type = tarfile.SYMTYPE
                            member.linkname = data.decode()
                            archive.addfile(member)
                        else:
                            member.size = len(data)
                            archive.addfile(member, io.BytesIO(data))
        digest = hashlib.sha256(self.archive.read_bytes()).hexdigest()
        self.patches[2].stop()
        self.patches[2] = patch.object(upstream_source, "ARCHIVE_SHA256", digest)
        self.patches[2].start()
        return digest

    def test_exact_archive_stages_then_revalidates_without_mutation(self):
        self.make_archive()
        upstream_source.ensure_source(self.source, self.cache_archive, self.archive)
        before = upstream_source._tree_inventory(self.source)
        upstream_source.ensure_source(self.source, self.cache_archive)
        self.assertEqual(before, upstream_source._tree_inventory(self.source))
        self.assertEqual(0o755, (self.source / "bin/run").stat().st_mode & 0o777)
        self.assertEqual(0o755, self.source.stat().st_mode & 0o777)
        self.assertTrue((self.source / "pyproject.toml").is_file())

    def test_existing_tree_with_pip_metadata_fails_closed_and_is_preserved(self):
        self.make_archive()
        upstream_source.ensure_source(self.source, self.cache_archive, self.archive)
        metadata = self.source / "pkg" / "VibeVoice.egg-info"
        metadata.mkdir()
        marker = metadata / "PKG-INFO"
        marker.write_text("generated by installer", encoding="utf-8")
        with self.assertRaises(upstream_source.SourceIntegrityError):
            upstream_source.ensure_source(self.source, self.cache_archive)
        self.assertEqual("generated by installer", marker.read_text(encoding="utf-8"))

    def test_corrupt_existing_source_is_never_overwritten(self):
        self.make_archive()
        upstream_source.ensure_source(self.source, self.cache_archive, self.archive)
        target = self.source / "pkg" / "__init__.py"
        target.write_text("foreign or damaged contents", encoding="utf-8")
        with self.assertRaises(upstream_source.SourceIntegrityError):
            upstream_source.ensure_source(self.source, self.cache_archive)
        self.assertEqual("foreign or damaged contents", target.read_text(encoding="utf-8"))

    def test_existing_directory_mode_mismatch_fails_closed(self):
        self.make_archive()
        upstream_source.ensure_source(self.source, self.cache_archive, self.archive)
        directory = self.source / "pkg"
        directory.chmod(0o700)
        with self.assertRaises(upstream_source.SourceIntegrityError):
            upstream_source.ensure_source(self.source, self.cache_archive)
        self.assertEqual(0o700, directory.stat().st_mode & 0o777)

    def test_archive_digest_mismatch_does_not_publish_or_stage(self):
        self.make_archive()
        self.archive.write_bytes(self.archive.read_bytes() + b"tamper")
        with self.assertRaises(upstream_source.SourceIntegrityError):
            upstream_source.ensure_source(self.source, self.cache_archive, self.archive)
        self.assertFalse(self.cache_archive.exists())
        self.assertFalse(self.source.exists())

    def test_symlink_member_is_rejected(self):
        self.make_archive(extra={f"{self.root_name}/escape": ("symlink", b"../../outside", 0o777)})
        with self.assertRaises(upstream_source.SourceIntegrityError):
            upstream_source.inventory_archive(self.archive)

    def test_traversal_member_is_rejected(self):
        self.make_archive(extra={f"{self.root_name}/../outside": ("file", b"bad", 0o644)})
        with self.assertRaises(upstream_source.SourceIntegrityError):
            upstream_source.inventory_archive(self.archive)

    def test_wrong_cached_archive_is_preserved_and_rejected(self):
        self.make_archive()
        self.cache_archive.write_bytes(b"existing cache bytes")
        with self.assertRaises(upstream_source.SourceIntegrityError):
            upstream_source.ensure_source(self.source, self.cache_archive, self.archive)
        self.assertEqual(b"existing cache bytes", self.cache_archive.read_bytes())
        self.assertFalse(self.source.exists())

    def test_import_origin_must_be_inside_verified_source(self):
        package = self.source / "vibevoice" / "__init__.py"
        package.parent.mkdir(parents=True)
        package.write_text("", encoding="utf-8")
        with patch.object(upstream_source.importlib.util, "find_spec", return_value=SimpleNamespace(origin=str(package))):
            upstream_source.verify_import_source(self.source)
        legacy = self.root / "legacy-source" / "vibevoice" / "__init__.py"
        legacy.parent.mkdir(parents=True)
        legacy.write_text("", encoding="utf-8")
        with patch.object(upstream_source.importlib.util, "find_spec", return_value=SimpleNamespace(origin=str(legacy))):
            with self.assertRaises(upstream_source.SourceIntegrityError):
                upstream_source.verify_import_source(self.source)

    def test_bootstrap_uses_pinned_tree_and_isolated_venv(self):
        bootstrap = Path(__file__).parents[2] / "dgx" / "gateway" / "bootstrap.sh"
        text = bootstrap.read_text(encoding="utf-8")
        self.assertIn("source-$SOURCE_COMMIT-$SOURCE_ARCHIVE_SHA256", text)
        self.assertIn("venv-$SOURCE_COMMIT-$SOURCE_ARCHIVE_SHA256", text)
        self.assertIn("verify_import_source", text)
        self.assertNotIn(" -e \"$CACHE/source\"", text)
        self.assertNotIn("$CACHE/source/.\"", text)


if __name__ == "__main__":
    unittest.main()
