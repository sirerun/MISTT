import Foundation
import XCTest
@testable import MISTTDesktop

final class RelayOperationalDiagnosticsTests: XCTestCase {
    private let line = "2026/11/06 15:00:00 INFO paired_startup phase=native_start error_class=failure native_code=capture_start_failed elapsed_ms=42 session_id=00112233-4455-6677-8899-aabbccddeeff"

    func testStartupAllowsOnlyKnownFieldsAndEnums() {
        XCTAssertEqual(RelayOperationalDiagnostics.startupRecord(line),
                       .init(phase: "native_start", errorClass: "failure", nativeCode: "capture_start_failed", elapsedMS: 42))
        for bad in [line + " token=private", line.replacingOccurrences(of: "native_start", with: "private/path"),
                    line.replacingOccurrences(of: "failure", with: "private_transcript"),
                    line.replacingOccurrences(of: "capture_start_failed", with: "token=private"),
                    line.replacingOccurrences(of: "elapsed_ms=42", with: "elapsed_ms=private"),
                    line.replacingOccurrences(of: "00112233-4455-6677-8899-aabbccddeeff", with: "/private/file")] {
            XCTAssertNil(RelayOperationalDiagnostics.startupRecord(bad))
        }
    }

    func testStaticErrorsAndBridgeFailuresExcludePrivateSuffixes() {
        XCTAssertEqual(RelayOperationalDiagnostics.finalErrorClass("native owner disconnected"), "native_disconnected")
        XCTAssertNil(RelayOperationalDiagnostics.finalErrorClass("native owner disconnected token=private"))
        XCTAssertEqual(RelayOperationalDiagnostics.failureClass("MISTT relay heartbeat expired."), "heartbeat_expired")
        XCTAssertEqual(RelayOperationalDiagnostics.failureClass("private transcript /file token"), "other")
    }

    func testBoundedReaderRecoversAfterOversizeLineAndChunkBoundaries() {
        final class Received: @unchecked Sendable {
            var lines: [String] = []
        }
        let received = Received()
        let reader = RelayDiagnosticLineReader { received.lines.append($0) }
        reader.append(Data(repeating: 65, count: 4096))
        reader.append(Data("\nnative owner ".utf8))
        reader.append(Data("disconnected\n".utf8))
        XCTAssertEqual(received.lines, ["native owner disconnected"])
    }
    func testExactGoMarshalStartupFixtureDecodesThroughLineReader() {
        // Generated by private 2fdbdae ipc.NativeMessage.MarshalJSON, not Swift encoding.
        let fixture = #"""
{"counter":100,"type":"heartbeat"}
{"capturing":false,"connected_clients":1,"muted":false,"reason":"user","revision":20,"type":"status","update_ready":false,"update_reserved":false}
{"call_audio":{"bundle_id":"com.openai.chat","include_helper_executables":["Contents/Frameworks/ChatGPT Helper (Renderer).app/Contents/MacOS/ChatGPT Helper (Renderer)"],"include_helpers":[]},"microphone":{"device":"default"},"request_id":"00112233-4455-6677-8899-aabbccddeeff","session_id":"00112233-4455-6677-8899-aabbccddeeff","sources":[{"source":"microphone","sample_rate_hz":16000,"channels":1,"encoding":"s16le"},{"source":"call_audio","sample_rate_hz":16000,"channels":1,"encoding":"s16le"}],"type":"capture_start"}
"""#
        final class Results: @unchecked Sendable { var success = 0; var failures = 0 }
        let results = Results()
        let reader = StatusLineReader { result in
            switch result {
            case .success: results.success += 1
            case .failure: results.failures += 1
            }
        }
        reader.append(Data((fixture + "\n").utf8))
        XCTAssertEqual(results.success, 3)
        XCTAssertEqual(results.failures, 0)
    }

    func testReaderReportsOnlyFirstFailureAndRecoversNoUntrustedMessages() {
        final class Results: @unchecked Sendable { var failures = 0; var successes = 0 }
        for first in [Data("not JSON\n".utf8), Data(repeating: 65, count: 131_073)] {
            let results = Results()
            let reader = StatusLineReader { result in
                switch result {
                case .success: results.successes += 1
                case .failure: results.failures += 1
                }
            }
            reader.append(first)
            reader.append(Data("{\"type\":\"heartbeat\",\"counter\":1}\n".utf8))
            reader.append(Data("private untrusted content\n".utf8))
            XCTAssertEqual(results.failures, 1)
            XCTAssertEqual(results.successes, 0)
        }
    }

    func testParserDiagnosticWhitelistsUnknownEnvelopeAndCodingKey() {
        let privateLine = Data(#"{"type":"private transcript token /path"}"#.utf8)
        let context = DecodingError.Context(codingPath: [], debugDescription: "private transcript token /path")
        struct Key: CodingKey { let stringValue: String; let intValue: Int? = nil; init?(stringValue: String) { self.stringValue = stringValue }; init?(intValue: Int) { return nil } }
        let diagnostic = RelayOperationalDiagnostics.classifyParserFailure(
            DecodingError.keyNotFound(Key(stringValue: "private/path")!, context), line: privateLine)
        XCTAssertEqual(diagnostic, .init(family: "missing_key", messageType: "unknown", missingKey: "other", byteCount: privateLine.count))
        XCTAssertEqual(RelayOperationalDiagnostics.classifyParserFailure(RelayReadError.lineTooLarge, line: Data()).family, "line_too_large")
        XCTAssertEqual(RelayOperationalDiagnostics.classifyParserFailure(RelayReadError.invalidMessage, line: Data()).family, "message_invariant")
    }

    func testGoStoppingFailureProjectionIsAcceptedWithoutUpdateAuthority() throws {
        // Actual exact-2fdbdae Service.stopPair(cause:) output, using synthetic input.
        let fixture = #"{"capturing":true,"connected_clients":0,"muted":false,"reason":"native_failure","revision":2,"type":"status","update_ready":false,"update_reserved":false}"#
        let status = try RelayStatus.decodeLine(Data(fixture.utf8))
        XCTAssertTrue(status.capturing)
        XCTAssertFalse(RelayShutdownReadiness.isReady(status: status, localCaptureClosed: true))
        for muted in [false, true] {
            let closing = RelayStatus(muted: muted, capturing: true, connectedClients: 1,
                                      reason: "native_failure", revision: 3, updateReady: false, updateReserved: false)
            XCTAssertNoThrow(try closing.validate())
            XCTAssertFalse(RelayShutdownReadiness.isReady(status: closing, localCaptureClosed: true))
            let unsafeUpdate = RelayStatus(muted: muted, capturing: true, connectedClients: 1,
                                          reason: "native_failure", revision: 3, updateReady: true, updateReserved: false)
            XCTAssertThrowsError(try unsafeUpdate.validate())
            let unsafeReservation = RelayStatus(muted: muted, capturing: true, connectedClients: 1,
                                               reason: "native_failure", revision: 3, updateReady: false, updateReserved: true)
            XCTAssertThrowsError(try unsafeReservation.validate())
        }
        let unmutedIdleFailure = RelayStatus(muted: false, capturing: false, connectedClients: 1,
                                            reason: "native_failure", revision: 3, updateReady: false, updateReserved: false)
        XCTAssertThrowsError(try unmutedIdleFailure.validate())
    }

}
